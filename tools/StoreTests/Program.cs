using ZarayskCosmetics;
using ZarayskVipSystem;

var root = Path.Combine(Path.GetTempPath(), "zaraysk-store-tests-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(root);
void Check(bool valid, string name) { if (!valid) throw new Exception(name); Console.WriteLine("PASS " + name); }
var cosmetics = new CosmeticsStore(new() { Database = new() { Provider = "json" } }, Path.Combine(root, "cosmetics.json"));
await cosmetics.InitializeAsync();
await cosmetics.GrantAsync(123, "knife", 2, 1);
await cosmetics.GrantAsync(123, "hat", 1, 0);
Check((await cosmetics.GetAsync(123)).Single(x => x.CosmeticId == "knife").Quantity == 2, "quantity grant");
await cosmetics.EquipAsync(123, "knife", ["knife"]);
await cosmetics.EquipAsync(123, "hat", ["hat"]);
Check((await cosmetics.GetAsync(123)).Count(x => x.Equipped) == 2, "independent cosmetic slots");
await cosmetics.EquipAsync(123, null, ["knife"]);
Check((await cosmetics.GetAsync(123)).Single(x => x.CosmeticId == "hat").Equipped, "weapon removal preserves other cosmetics");
await cosmetics.RemoveAsync(123, "knife", 2);
Check(!(await cosmetics.GetAsync(123)).Any(x => x.CosmeticId == "knife"), "zero quantity loses access");
var reopened = new CosmeticsStore(new() { Database = new() { Provider = "json" } }, Path.Combine(root, "cosmetics.json"));
Check((await reopened.GetAsync(123)).Single().CosmeticId == "hat", "inventory survives restart");
var vip = new VipStore(new() { Database = new() { Provider = "json" } }, Path.Combine(root, "vip.json"));
await vip.InitializeAsync();
await vip.UpsertAsync(123, "Tester", "PREMIUM", 1);
Check((await vip.GetAsync(123)) is { IsActive: true, GroupId: "PREMIUM" }, "timed VIP access");
await vip.SavePreferencesAsync(123, new() { Fov = 105 });
Check((await vip.GetAsync(123))!.Preferences.Fov == 105, "VIP preferences persist");
await vip.RemoveAsync(123);
Check(await vip.GetAsync(123) is null, "VIP revocation");
Check(ZarayskCosmeticsPlugin.WeaponMatches("weapon_knife", "weapon_knife_t"), "T knife receives custom model");
Check(ZarayskCosmeticsPlugin.WeaponMatches("weapon_knife", "weapon_knife_butterfly"), "knife variants share cosmetic slot");
Check(!ZarayskCosmeticsPlugin.WeaponMatches("weapon_ak47", "weapon_m4a1"), "weapon catalog cannot replace wrong weapon");
var flyingPet = new CosmeticDefinition { Type = "pet", ModelPath = "models/pets/dota2/owl_flying/owl.vmdl", OffsetForward = -55, OffsetRight = 28, OffsetUp = 8 };
Check(ZarayskCosmeticsPlugin.IsFlyingPet(flyingPet), "flying Dota pet is detected from model path");
var flyingPosition = ZarayskCosmeticsPlugin.CosmeticPosition(100, 200, 20, 0, flyingPet, 0);
Check(Math.Abs(flyingPosition.X - 45) < 0.01f && Math.Abs(flyingPosition.Y - 228) < 0.01f && Math.Abs(flyingPosition.Z - 68) < 0.01f, "flying pet follows behind, beside and above player");
var groundPet = new CosmeticDefinition { Type = "pet", ModelPath = "models/pets/dota2/owl/owl.vmdl" };
var groundPosition = ZarayskCosmeticsPlugin.CosmeticPosition(0, 0, 10, 90, groundPet, 0);
Check(Math.Abs(groundPosition.X + 28) < 0.01f && Math.Abs(groundPosition.Y + 55) < 0.01f && Math.Abs(groundPosition.Z - 18) < 0.01f, "ground pet receives safe default follow offsets");
Check(ZarayskVipSystemPlugin.AccumulateDamage(27, 10f, 10.35f, 3f, 13) == 40, "damage HUD sums hits inside display window");
Check(ZarayskVipSystemPlugin.AccumulateDamage(40, 10f, 13.01f, 3f, 9) == 9, "damage HUD starts a new total after timeout");
Check(ZarayskVipSystemPlugin.AccumulateDamage(10, 10f, 14.01f, 99f, 5) == 5, "damage HUD duration is clamped to four seconds");
Console.WriteLine("Test data: " + root);
